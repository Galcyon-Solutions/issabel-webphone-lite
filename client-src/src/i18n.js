/** Traduce una clave; {n} y {m} se reemplazan con params. Sin clave en el idioma: espanol; sin clave en ninguno: la clave. */
export function makeT(lang) {
  const table = MESSAGES[lang] || MESSAGES.es;
  return (key, params) => {
    let s = table[key] != null ? table[key] : (MESSAGES.es[key] != null ? MESSAGES.es[key] : key);
    if (params) for (const k of Object.keys(params)) s = s.split('{' + k + '}').join(String(params[k]));
    return s;
  };
}

/** Idioma de un codigo ("pt", "pt-BR", "en-US", "es_MX") o null si no hay traduccion. */
export function matchLang(code) {
  const c = String(code || '').replace('_', '-').toLowerCase();
  if (!c) return null;
  if (c === 'pt-br' || c.startsWith('pt')) return 'pt-BR';
  const base = c.slice(0, 2);
  return MESSAGES[base] ? base : null;
}

/** Orden: opcion lang, atributo lang de la pagina anfitriona, idioma del navegador, respaldo es. */
export function pickLang(requested) {
  const nav = (typeof navigator !== 'undefined' && (navigator.languages && navigator.languages[0] || navigator.language)) || '';
  return matchLang(requested) || matchLang(document.documentElement.getAttribute('lang')) || matchLang(nav) || 'es';
}

/** Hora local en el idioma de la persona (por ejemplo para el informe de soporte). */
export function fmtTime(lang, date) {
  try { return new Intl.DateTimeFormat(lang, { dateStyle: 'medium', timeStyle: 'medium' }).format(date); } catch (e) { return date.toISOString(); }
}
